/** Proper RFC4180-ish CSV parser, shared between the targets CSV importer and the settings
 *  rubric-upload viewer — handles quoted fields, doubled `""` as a literal quote, and newlines
 *  (both bare and quoted) as row separators only outside quotes, so a naive split(',')/split('\n')
 *  never corrupts a quoted multi-line cell or a quoted comma-separated list inside one field. */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        inQuotes = false;
      } else {
        field += c;
      }
      continue;
    }
    if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\r') {
      // skip — paired \n (or a lone \r) below ends the row
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += c;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}
